export async function register() {
  if (process.env.NEXT_RUNTIME === 'nodejs' && process.env.NEXT_PHASE !== 'phase-production-build') {
    const { ensureLeadershipGroupSync } = await import('./lib/units/leadership-groups-server')
    ensureLeadershipGroupSync()
    const { ensureClipCompressionWorker } = await import('./lib/media/clip-compression')
    ensureClipCompressionWorker()
    const { ensurePhotoCatalogSync } = await import('./lib/investigations/investigation-photos')
    ensurePhotoCatalogSync()
    const { ensureHirePingCleanup } = await import('./lib/discord/hire-ping')
    ensureHirePingCleanup()
    const { ensureUploadCleanupWorker } = await import('./lib/media/upload-sessions')
    ensureUploadCleanupWorker()
    const { ensureManualDutyWorker } = await import('./lib/duty/manual-duty')
    ensureManualDutyWorker()
    const { ensureDutyStatusPanelRefresher } = await import('./lib/discord/discord-integration')
    ensureDutyStatusPanelRefresher()
    const { ensureDiscordGateway } = await import('./lib/discord/discord-gateway')
    ensureDiscordGateway()
    const { ensureAgentStatusAutomationWorker } = await import('./lib/agents/absence-status')
    ensureAgentStatusAutomationWorker()
    const { ensureWeeklyReportWorker } = await import('./lib/duty/weekly-report-server')
    ensureWeeklyReportWorker()
    const { ensureStorageLogWorker } = await import('./lib/storage-logs/storage-logs-server')
    ensureStorageLogWorker()
    const [{ ensureDatabaseBackupScheduler }, { prisma }] = await Promise.all([import('./lib/core/database-backup'), import('./lib/prisma')])
    ensureDatabaseBackupScheduler(prisma)
    const { migrateContractSignatures } = await import('./lib/contracts/contract-signature-migration')
    void migrateContractSignatures()
      .then((count) => { if (count > 0) console.log(`[Contracts] ${count} fehlende Unterschriftszeilen angelegt`) })
      .catch((error) => console.error('[Contracts] Unterschriftszeilen konnten nicht angelegt werden:', error))
  }
}
